package org.gemini.ui.forge.service.studio

import kotlinx.serialization.json.*
import org.gemini.ui.forge.data.TemplateFile
import org.gemini.ui.forge.model.ui.*
import org.gemini.ui.forge.ui.uistudio.model.UIAssetItem
import org.gemini.ui.forge.ui.uistudio.model.UIAssetLibrary
import org.gemini.ui.forge.utils.AppLogger
import org.gemini.ui.forge.utils.bindParents

/**
 * 界面全自动装配与排版落地核心服务。
 *
 * 核心职能：
 * 1. 响应大模型发起的 [apply_view_layout] 本地工具调用；
 * 2. 贯彻全屏背景自愈、局部相对坐标系与纯容器铁律；
 * 3. 自动根据切片文件名 (assetFileName) 匹配工程素材库物理资源；
 * 4. 递归装配 UIBlock 树并构建完整 UIPage 视图对象。
 */
object UiStudioLayoutService {
    private const val TAG = "UiStudioLayoutService"

    /**
     * 工具执行返回结果
     */
    data class ApplyLayoutResult(
        val isSuccess: Boolean,
        val viewName: String,
        val blockCount: Int,
        val createdPage: UIPage? = null,
        val summary: String = "",
        val errorMessage: String? = null
    )

    /**
     * 将大模型输出的 JSON 参数解析并装配为真实的 UIPage 页面实体
     */
    fun assembleViewPage(
        projectId: String,
        assetLibrary: UIAssetLibrary,
        args: JsonObject
    ): ApplyLayoutResult {
        return try {
            val rawName = args["viewName"]?.jsonPrimitive?.contentOrNull?.trim()
            val viewName = if (rawName.isNullOrBlank()) "AutoGeneratedView" else rawName
            val width = args["width"]?.jsonPrimitive?.intOrNull?.toFloat() ?: 1280f
            val height = args["height"]?.jsonPrimitive?.intOrNull?.toFloat() ?: 720f

            val rawBlocks = args["blocks"]?.jsonArray ?: JsonArray(emptyList())

            // 建立素材库文件名快速索引 (忽略大小写)
            val assetMap = mutableMapOf<String, UIAssetItem>()
            assetLibrary.items.forEach { asset ->
                assetMap[asset.name.lowercase()] = asset
                val cleanName = asset.name.substringBeforeLast('.').lowercase()
                assetMap[cleanName] = asset
            }

            // 递归解析图元列表
            val assembledBlocks = mutableListOf<UIBlock>()
            for (element in rawBlocks) {
                val blockObj = element as? JsonObject ?: continue
                parseBlockRecursive(blockObj, projectId, assetMap, assembledBlocks)
            }

            // 构建 UIPage 并执行全屏背景等自愈治理
            val initialPage = UIPage(
                id = "page_${viewName.replace(" ", "_")}",
                nameStr = viewName,
                width = width,
                height = height,
                blocks = assembledBlocks
            )

            // 执行核心规范自愈：贯彻全屏游戏背景底图规范，绑定父级引用
            val postProcessedPage = initialPage.postProcess()
            postProcessedPage.blocks.bindParents()

            val totalBlocksCount = countAllBlocks(postProcessedPage.blocks)
            AppLogger.i(TAG, "成功为工程 [$projectId] 装配视图 [$viewName]，包含 $totalBlocksCount 个图元")

            ApplyLayoutResult(
                isSuccess = true,
                viewName = viewName,
                blockCount = totalBlocksCount,
                createdPage = postProcessedPage,
                summary = "成功装配视图 [$viewName] ($width x $height)，包含 $totalBlocksCount 个组件图元"
            )
        } catch (e: Exception) {
            AppLogger.e(TAG, "执行 apply_view_layout 装配异常", e)
            ApplyLayoutResult(
                isSuccess = false,
                viewName = "ErrorView",
                blockCount = 0,
                errorMessage = e.message ?: "未知排版解析异常"
            )
        }
    }

    /**
     * 递归解析单个图元对象
     */
    private fun parseBlockRecursive(
        obj: JsonObject,
        projectId: String,
        assetMap: Map<String, UIAssetItem>,
        outList: MutableList<UIBlock>
    ) {
        val id = obj["id"]?.jsonPrimitive?.contentOrNull ?: "block_${outList.size + 1}"
        val typeStr = obj["type"]?.jsonPrimitive?.contentOrNull ?: "CONTAINER"
        val type = parseBlockType(typeStr)

        val x = obj["x"]?.jsonPrimitive?.floatOrNull ?: 0f
        val y = obj["y"]?.jsonPrimitive?.floatOrNull ?: 0f
        val w = obj["width"]?.jsonPrimitive?.floatOrNull ?: 100f
        val h = obj["height"]?.jsonPrimitive?.floatOrNull ?: 100f
        val bounds = SerialRect(x, y, w, h)

        val isPureContainer = obj["isPureContainer"]?.jsonPrimitive?.booleanOrNull
            ?: (type == UIBlockType.CONTAINER)

        // 匹配素材库切片
        val assetFileName = obj["assetFileName"]?.jsonPrimitive?.contentOrNull?.trim()
        var boundFile: TemplateFile? = null
        if (!assetFileName.isNullOrBlank()) {
            val matchedAsset = assetMap[assetFileName.lowercase()]
                ?: assetMap[assetFileName.substringBeforeLast('.').lowercase()]
            if (matchedAsset != null) {
                val path = "templates/$projectId/assets/${matchedAsset.relativePath}"
                boundFile = TemplateFile(path)
            }
        }

        // 解析嵌套子组件
        val childBlocks = mutableListOf<UIBlock>()
        val rawChildren = obj["children"]?.jsonArray
        if (rawChildren != null && rawChildren.isNotEmpty()) {
            for (childElement in rawChildren) {
                val childObj = childElement as? JsonObject ?: continue
                parseBlockRecursive(childObj, projectId, assetMap, childBlocks)
            }
        }

        val block = UIBlock(
            id = id,
            type = type,
            bounds = bounds,
            isPureContainer = isPureContainer,
            referenceImage = boundFile,
            currentImageUri = boundFile,
            children = childBlocks
        )
        outList.add(block)
    }

    /**
     * 容错解析图元类型枚举
     */
    private fun parseBlockType(typeStr: String): UIBlockType {
        val upper = typeStr.uppercase().trim()
        return try {
            UIBlockType.valueOf(upper)
        } catch (_: Exception) {
            when {
                upper.contains("BG") || upper.contains("BACK") -> UIBlockType.BACKGROUND
                upper.contains("BTN") || upper.contains("BUTTON") -> UIBlockType.BUTTON
                upper.contains("TEXT") || upper.contains("LABEL") -> UIBlockType.TEXT
                upper.contains("SLOT") || upper.contains("REEL") -> UIBlockType.REEL
                upper.contains("SPIN") -> UIBlockType.SPIN_BUTTON
                else -> UIBlockType.CONTAINER
            }
        }
    }

    /**
     * 递归统计整棵树的图元总数
     */
    fun countAllBlocks(blocks: List<UIBlock>): Int {
        var count = blocks.size
        for (b in blocks) {
            if (b.children.isNotEmpty()) {
                count += countAllBlocks(b.children)
            }
        }
        return count
    }
}
